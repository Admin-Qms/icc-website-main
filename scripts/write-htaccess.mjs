// Writes an Apache .htaccess with the same 301 redirects as vercel.json, for the
// cPanel backup host. vercel.json stays the single list of redirects; the GitHub
// Action runs this after `next build` so out/ carries the rules to public_html.
//
//   node scripts/write-htaccess.mjs [vercel.json] [out/.htaccess]

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const escapeRegex = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** Converts one vercel.json redirect source to an anchored Apache regex. */
export function sourceToRegex(source) {
  if (!source.startsWith("/"))
    throw new Error(`Redirect source must start with "/": ${source}`);
  const wildcard = source.match(/^(.*?)\/:[a-zA-Z]+\*$/);
  if (wildcard) return `^${escapeRegex(wildcard[1])}(?:/.*)?$`;
  if (/[:()*?]/.test(source))
    throw new Error(`Unsupported redirect source pattern: ${source}`);
  // Match with or without the trailing slash, as Vercel serves both forms.
  return `^${escapeRegex(source.replace(/\/$/, ""))}/?$`;
}

export function buildHtaccess(redirects) {
  const lines = [
    "# Generated by scripts/write-htaccess.mjs from vercel.json. Do not edit by hand.",
    "<IfModule mod_alias.c>",
  ];
  for (const r of redirects) {
    if (/[:*]/.test(r.destination))
      throw new Error(`Unsupported redirect destination: ${r.destination}`);
    const status = r.statusCode ?? (r.permanent === false ? 302 : 301);
    lines.push(
      `  RedirectMatch ${status} "${sourceToRegex(r.source)}" "${r.destination}"`,
    );
  }
  lines.push("</IfModule>", "");
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [src = "vercel.json", dest = "out/.htaccess"] = process.argv.slice(2);
  const { redirects = [] } = JSON.parse(readFileSync(src, "utf8"));
  writeFileSync(dest, buildHtaccess(redirects));
  console.log(`Wrote ${redirects.length} redirects to ${dest}`);
}
